<td style="text-align: left; background-color: white; vertical-align: top; width: 435.583px;"><br>
<div><span><span>CORMAS</span> is an Agent-Based Modelling
(ABM) platform tailored preferentially to renewable
resource management. <br>
</span></div>
<div><span>Cormas is intended to facilitate the design of
ABM, as well as monitor and analyse simulations. It is
based on the VisualWorks programming environment which
enables the development of models in Smalltalk. Cormas
is a framework from which, by specialization and
refining, users can create specific entities for their
own model.<br>
</span></div>
<br>
- CORMAS is a free Open Source Software. Its last release
(02/2023) <a title="Download" href="en/outil/outil.htm" target="_blank">can
be <b>downloaded </b>here</a>. <br>
