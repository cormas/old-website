<ul>
<li><b>Key points</b><br>
</li>
<ul>
<li>MISS-ABMS is multi-cultural in terms of background and
nationalities of the trainers and participants</li>
<li>MISS-ABMS promotes a collaborative practice of modelling and
simulation</li>
<li>MISS-ABMS is multi-platform: <a href="http://cormas.cirad.fr/indexeng.htm">Cormas</a>,
<a href="https://gama-platform.org">Gama</a> or <a href="https://ccl.northwestern.edu/netlogo/index.shtml">NetLogo</a>
can be choosen</li>
<li>MISS-ABMS presents the different stages of an ABM process,
with a focus on model design and implementation</li>
<li>MISS-ABMS offers a significant time for group work to design
and implement an ABM (see the <a href="pdf/leaflet-miss-abms-2021.pdf"
title="leaflet">leaflet</a>
or watch the <a href="https://vimeo.com/254868269">presentation
video</a>). </li>
</ul>
<li><b>For who</b><br>
</li>
<ul>
<li>Each year we enjoy having participants with very
heterogeneous profiles in terms of age, nationality,
scientific background and experience in modelling or coding.
Beginners in ABM who are planning to participate in a
modelling project in the months following the training are
welcomed.</li>
<li>If you have any concern regarding your participation, feel
free to ask at:<br>
<u>miss-abms_organizers[at]agropolis[dot]fr</u></li>
</ul>
